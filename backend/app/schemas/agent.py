class AttackCategory(str, Enum):
    """The 6 adversarial attack families defined in CYBER-02 / PRD."""

    PROMPT_INJECTION = "prompt_injection"
    EMAIL_INDIRECT = "email_indirect"
    WEBPAGE_INDIRECT = "webpage_indirect"
    DOCUMENT_INDIRECT = "document_indirect"
    DATA_EXFILTRATION = "data_exfiltration"
    UNAUTHORIZED_PAYMENT = "unauthorized_payment"

    # Aliases for compatibility
    PRIVILEGE_ESCALATION = "privilege_escalation"
    TOOL_ABUSE = "tool_abuse"
    EVASION = "evasion"
    SOCIAL_ENGINEERING = "social_engineering"


class RedTeamAttack(BaseModel):
    """Structured output generated by the Red Team agent node.

    Defines the adversarial payload and attack metadata.
    """

    attack_id: str = Field(
        min_length=3,
        max_length=64,
        description="Unique identifier for this attack payload (e.g. atk-123456)",
    )
    category: AttackCategory = Field(
        description="Adversarial attack category across the 6 PRD families"
    )
    intended_goal: str = Field(
        min_length=3,
        max_length=500,
        description="The adversary's explicit objective for this simulation step",
    )
    strategy_summary: str = Field(
        min_length=3,
        max_length=500,
        description="Brief conceptual summary of the attack technique and evasion approach",
    )
    payload_text: str = Field(
        min_length=1,
        max_length=5000,
        description="The actual text/prompt injected towards the Target AI",
    )
    target_surface: str = Field(
        default="user_prompt",
        description="Target attack surface: user_prompt | email_body | web_page | document_content | system_prompt",
    )


