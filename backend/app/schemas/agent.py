# ---------------------------------------------------------------------------
# Blue Team Guardian Threat Evaluation Schemas
# ---------------------------------------------------------------------------


class GuardianAssessment(BaseModel):
    """Structured threat evaluation output from the Blue Team Guardian agent node."""

    threat_detected: bool = Field(description="True if an adversarial threat or anomalous intent is detected")
    risk_score: float = Field(ge=0.0, le=1.0, description="Normalized risk score from 0.0 (safe) to 1.0 (critical threat)")
    severity: ThreatSeverity = Field(description="Threat classification severity: LOW | MEDIUM | HIGH | CRITICAL")
    indicators: List[str] = Field(default_factory=list, description="Specific threat signatures or MITRE-like indicators")
    explanation: str = Field(
        min_length=3,
        description="Technical rationale for the threat rating",
    )
    recommended_action: GuardianRecommendation = Field(
        default=GuardianRecommendation.ALLOW,
        description="Recommended enforcement advisory: ALLOW | MONITOR | BLOCK | REQUIRE_APPROVAL",
    )

    @classmethod
    def fail_closed_fallback(cls, reason: str = "Guardian LLM failure — failing closed") -> "GuardianAssessment":
        """Return a strictly fail-closed security assessment when model evaluation fails."""
        return cls(
            threat_detected=True,
            risk_score=1.0,
            severity=ThreatSeverity.CRITICAL,
            indicators=["LLM_EVALUATION_FAILURE", "FAIL_CLOSED_TRIGGERED"],
            explanation=f"Fail-closed defensive fallback activated: {reason}",
            recommended_action=GuardianRecommendation.BLOCK,
        )


# ---------------------------------------------------------------------------
# Token Metrics & Execution Result Envelope
# ---------------------------------------------------------------------------


class TokenUsage(BaseModel):
    """Token consumption metrics for observability and cost tracking."""

    input_tokens: int = Field(default=0, ge=0)
    output_tokens: int = Field(default=0, ge=0)
    total_tokens: int = Field(default=0, ge=0)


class GeminiExecutionResult(BaseModel, Generic[T]):
    """Standardized result envelope for all Gemini LLM invocations."""

    data: Optional[T] = Field(default=None, description="Parsed and validated Pydantic model")
    raw_text: str = Field(default="", description="Raw response text from Gemini")
    model_id: str = Field(description="Identifier of model used (e.g. gemini-3.8-flash)")
    latency_ms: int = Field(default=0, ge=0, description="Invocation latency in milliseconds")
    usage: TokenUsage = Field(default_factory=TokenUsage, description="Token consumption metrics")
    is_fallback: bool = Field(default=False, description="True if result was generated via fallback handler")
    error: Optional[str] = Field(default=None, description="Error message if an exception was caught")

