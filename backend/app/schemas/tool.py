"""Tool Action Proposal and Target AI Schemas for CYBER HUNT.

Defines the declarative tool invocation contract produced by the Target AI.
The Target AI ONLY recommends actions; it never executes them.
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class ToolName(str, Enum):
    """Synthetic sandbox tool identifiers."""

    EMAIL = "email"
    BROWSER = "browser"
    FILE = "file"
    PAYMENT = "payment"
    NONE = "none"


class ToolActionProposal(BaseModel):
    """Declarative specification of an intended synthetic sandbox tool operation."""

    action_id: str = Field(
        min_length=3,
        max_length=64,
        description="Unique identifier for this action proposal (e.g. act-read-inbox)",
    )
    tool_name: ToolName = Field(
        default=ToolName.NONE,
        description="Target synthetic tool to invoke: email | browser | file | payment | none",
    )
    operation: str = Field(
        min_length=1,
        max_length=64,
        description="Specific tool operation (e.g. read_inbox, send_email, transfer_funds, read_file)",
    )
    parameters: Dict[str, Any] = Field(
        default_factory=dict,
        description="Parameters passed to the mock tool sandbox",
    )
    rationale: str = Field(
        min_length=3,
        max_length=500,
        description="Security/functional rationale justifying why this tool action is required",
    )


class TargetAIResponse(BaseModel):
    """Structured completion generated by the Target AI agent.

    Contains conversational user response and an optional tool action proposal.
    """

    thought_process: str = Field(
        max_length=500,
        description="Concise high-level decision summary explaining the chosen response path. Never raw chain of thought.",
    )
    user_response: str = Field(
        min_length=1,
        max_length=4000,
        description="Natural language conversational response returned to the simulated user",
    )
    proposed_action: Optional[ToolActionProposal] = Field(
        default=None,
        description="Declarative tool proposal if external data/operation is needed, else None",
    )

